#!/usr/bin/env python3
"""Build a pacman-compatible Arch Linux .pkg.tar.zst package for Kasumi."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import os
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path


PKGNAME = "kasumi"
PKGDESC = (
    "Multi-device encrypted bidirectional file synchronization without a dedicated server"
)
PKGURL = "https://github.com/auanK/kasumi"
PACKAGER = "auanK <https://github.com/auanK/kasumi>"
DEPENDS = ("glibc", "gcc-libs")
OPTDEPENDS = (
    "rclone: remote cloud storage backends",
    "libsecret: GNOME Keyring / Secret Service vault storage",
    "kwallet: KDE KWallet vault storage",
)


def _digests(data: bytes) -> tuple[str, str]:
    return (
        hashlib.md5(data).hexdigest(),
        hashlib.sha256(data).hexdigest(),
    )


def _render_pkginfo(
    *,
    version: str,
    pkgrel: int,
    arch: str,
    builddate: int,
    installed_size: int,
) -> bytes:
    lines = [
        "# Generated by scripts/build_arch_package.py",
        f"pkgname = {PKGNAME}",
        f"pkgbase = {PKGNAME}",
        "xdata = pkgtype=pkg",
        f"pkgver = {version}-{pkgrel}",
        f"pkgdesc = {PKGDESC}",
        f"url = {PKGURL}",
        f"builddate = {builddate}",
        f"packager = {PACKAGER}",
        f"size = {installed_size}",
        f"arch = {arch}",
        "license = MIT",
    ]
    lines.extend(f"depend = {dep}" for dep in DEPENDS)
    lines.extend(f"optdepend = {opt}" for opt in OPTDEPENDS)
    return ("\n".join(lines) + "\n").encode("utf-8")


def _render_mtree(
    *,
    builddate: int,
    pkginfo_bytes: bytes,
    bin_bytes: bytes,
    license_bytes: bytes,
    notices_bytes: bytes,
    install_bytes: bytes | None = None,
    desktop_bytes: bytes | None = None,
) -> bytes:
    def file_line(relpath: str, payload: bytes, mode: str | None = None) -> str:
        md5_hex, sha256_hex = _digests(payload)
        mode_part = f" mode={mode}" if mode is not None else ""
        return (
            f"./{relpath} time={builddate}.0 size={len(payload)}{mode_part} "
            f"md5digest={md5_hex} sha256digest={sha256_hex}"
        )

    def dir_line(relpath: str) -> str:
        return f"./{relpath} time={builddate}.0 mode=755 type=dir"

    lines = [
        "#mtree",
        "/set type=file uid=0 gid=0 mode=644",
        file_line(".PKGINFO", pkginfo_bytes),
    ]
    if install_bytes is not None:
        lines.append(file_line(".INSTALL", install_bytes))
    lines.extend([
        dir_line("usr"),
        dir_line("usr/bin"),
        file_line("usr/bin/kasumi", bin_bytes, mode="755"),
        dir_line("usr/share"),
    ])
    if desktop_bytes is not None:
        lines.extend([
            dir_line("usr/share/applications"),
            file_line("usr/share/applications/kasumi.desktop", desktop_bytes),
        ])
    lines.extend([
        dir_line("usr/share/licenses"),
        dir_line(f"usr/share/licenses/{PKGNAME}"),
        file_line(f"usr/share/licenses/{PKGNAME}/LICENSE", license_bytes),
        file_line(
            f"usr/share/licenses/{PKGNAME}/THIRD_PARTY_NOTICES.md", notices_bytes
        ),
    ])
    raw = ("\n".join(lines) + "\n").encode("utf-8")
    return gzip.compress(raw, mtime=0)


def _add_file(
    archive: tarfile.TarFile, name: str, data: bytes, mode: int, mtime: int
) -> None:
    info = tarfile.TarInfo(name=name)
    info.type = tarfile.REGTYPE
    info.size = len(data)
    info.mode = mode
    info.uid = 0
    info.gid = 0
    info.uname = "root"
    info.gname = "root"
    info.mtime = mtime
    archive.addfile(info, io.BytesIO(data))


def _add_dir(archive: tarfile.TarFile, name: str, mtime: int) -> None:
    info = tarfile.TarInfo(name=name)
    info.type = tarfile.DIRTYPE
    info.size = 0
    info.mode = 0o755
    info.uid = 0
    info.gid = 0
    info.uname = "root"
    info.gname = "root"
    info.mtime = mtime
    archive.addfile(info)


def build_arch_tar_bytes(
    *,
    binary_path: Path,
    version: str,
    license_path: Path,
    notices_path: Path,
    install_script_path: Path | None = None,
    desktop_entry_path: Path | None = None,
    pkgrel: int = 1,
    arch: str = "x86_64",
    builddate: int | None = None,
) -> bytes:
    """Assemble the uncompressed Arch Linux package tar stream in memory."""
    if builddate is None:
        epoch = os.environ.get("SOURCE_DATE_EPOCH")
        builddate = int(epoch) if epoch else int(time.time())

    bin_bytes = binary_path.read_bytes()
    license_bytes = license_path.read_bytes()
    notices_bytes = notices_path.read_bytes()
    install_bytes = (
        install_script_path.read_bytes().replace(b"\r\n", b"\n")
        if install_script_path is not None
        else None
    )
    desktop_bytes = (
        desktop_entry_path.read_bytes().replace(b"\r\n", b"\n")
        if desktop_entry_path is not None
        else None
    )

    installed_size = (
        len(bin_bytes)
        + len(license_bytes)
        + len(notices_bytes)
        + (len(desktop_bytes) if desktop_bytes is not None else 0)
    )
    pkginfo_bytes = _render_pkginfo(
        version=version,
        pkgrel=pkgrel,
        arch=arch,
        builddate=builddate,
        installed_size=installed_size,
    )
    mtree_bytes = _render_mtree(
        builddate=builddate,
        pkginfo_bytes=pkginfo_bytes,
        bin_bytes=bin_bytes,
        license_bytes=license_bytes,
        notices_bytes=notices_bytes,
        install_bytes=install_bytes,
        desktop_bytes=desktop_bytes,
    )

    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w", format=tarfile.PAX_FORMAT) as archive:
        _add_file(archive, ".PKGINFO", pkginfo_bytes, 0o644, builddate)
        _add_file(archive, ".MTREE", mtree_bytes, 0o644, builddate)
        if install_bytes is not None:
            _add_file(archive, ".INSTALL", install_bytes, 0o644, builddate)
        _add_dir(archive, "usr", builddate)
        _add_dir(archive, "usr/bin", builddate)
        _add_file(archive, "usr/bin/kasumi", bin_bytes, 0o755, builddate)
        _add_dir(archive, "usr/share", builddate)
        if desktop_bytes is not None:
            _add_dir(archive, "usr/share/applications", builddate)
            _add_file(
                archive,
                "usr/share/applications/kasumi.desktop",
                desktop_bytes,
                0o644,
                builddate,
            )
        _add_dir(archive, "usr/share/licenses", builddate)
        _add_dir(archive, f"usr/share/licenses/{PKGNAME}", builddate)
        _add_file(
            archive,
            f"usr/share/licenses/{PKGNAME}/LICENSE",
            license_bytes,
            0o644,
            builddate,
        )
        _add_file(
            archive,
            f"usr/share/licenses/{PKGNAME}/THIRD_PARTY_NOTICES.md",
            notices_bytes,
            0o644,
            builddate,
        )
    return buffer.getvalue()


def build_arch_package(
    *,
    binary_path: Path,
    version: str,
    output_path: Path,
    license_path: Path,
    notices_path: Path,
    install_script_path: Path | None = None,
    desktop_entry_path: Path | None = None,
    pkgrel: int = 1,
    arch: str = "x86_64",
    builddate: int | None = None,
    zstd_exe: str | None = None,
) -> Path:
    """Write either an uncompressed .tar or a zstd-compressed .pkg.tar.zst package."""
    tar_bytes = build_arch_tar_bytes(
        binary_path=binary_path,
        version=version,
        license_path=license_path,
        notices_path=notices_path,
        install_script_path=install_script_path,
        desktop_entry_path=desktop_entry_path,
        pkgrel=pkgrel,
        arch=arch,
        builddate=builddate,
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    if output_path.name.endswith(".tar"):
        output_path.write_bytes(tar_bytes)
        return output_path

    if not output_path.name.endswith(".pkg.tar.zst"):
        raise ValueError(f"unsupported Arch package extension: {output_path.name}")

    zstd = zstd_exe or shutil.which("zstd")
    if not zstd:
        raise FileNotFoundError(
            "zstd executable not found; install zstd or output uncompressed .tar"
        )

    proc = subprocess.run(
        [zstd, "-T0", "-19", "--quiet", "--force", "-", "-o", str(output_path)],
        input=tar_bytes,
        capture_output=True,
        check=False,
    )
    if proc.returncode != 0:
        stderr = proc.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(f"zstd compression failed ({proc.returncode}): {stderr}")
    return output_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--license", type=Path, default=Path("LICENSE"))
    parser.add_argument(
        "--notices", type=Path, default=Path("THIRD_PARTY_NOTICES.md")
    )
    parser.add_argument("--install-script", type=Path, default=None)
    parser.add_argument("--desktop-entry", type=Path, default=None)
    parser.add_argument("--pkgrel", type=int, default=1)
    parser.add_argument("--arch", default="x86_64")
    parser.add_argument("--builddate", type=int, default=None)
    parser.add_argument("--zstd", default=None)
    args = parser.parse_args(argv)

    build_arch_package(
        binary_path=args.binary,
        version=args.version,
        output_path=args.output,
        license_path=args.license,
        notices_path=args.notices,
        install_script_path=args.install_script,
        desktop_entry_path=args.desktop_entry,
        pkgrel=args.pkgrel,
        arch=args.arch,
        builddate=args.builddate,
        zstd_exe=args.zstd,
    )
    print(f"built Arch package {args.output} ({args.version}-{args.pkgrel}, {args.arch})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
