#!/usr/bin/env python3
"""
Generates generated/application/webui_embedded.hpp containing the built Web UI
static assets from web/dist/ for single-binary serving by the Kasumi daemon.
"""

import argparse
import mimetypes
import sys
from pathlib import Path

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".mjs": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
    ".txt": "text/plain; charset=utf-8",
    ".wasm": "application/wasm",
}


def detect_content_type(path: Path) -> str:
    ext = path.suffix.lower()
    if ext in CONTENT_TYPES:
        return CONTENT_TYPES[ext]
    guessed, _ = mimetypes.guess_type(path.name)
    return guessed or "application/octet-stream"


def format_byte_array(symbol: str, data: bytes) -> str:
    if not data:
        return f"inline constexpr std::uint8_t {symbol}[1] = {{0}};\n"
    lines: list[str] = [f"inline constexpr std::uint8_t {symbol}[{len(data)}] = {{"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


def escape_cpp_string(value: str) -> str:
    for ch in value:
        if ord(ch) < 0x20 or ord(ch) == 0x7F:
            raise ValueError(f"Unsupported control character in metadata string: {value!r}")
    return value.replace("\\", "\\\\").replace('"', '\\"')


def generate_header(dist_dir: Path, enabled: bool) -> str:
    files: list[tuple[str, str, bytes, bool]] = []
    if enabled and (dist_dir / "index.html").is_file():
        for file_path in sorted(dist_dir.rglob("*")):
            if not file_path.is_file():
                continue
            rel = file_path.relative_to(dist_dir).as_posix()
            if rel.endswith(".map"):
                continue
            url_path = "/" + rel
            content_type = detect_content_type(file_path)
            immutable = url_path.startswith("/assets/")
            files.append((url_path, content_type, file_path.read_bytes(), immutable))

    available = "true" if files else "false"
    parts: list[str] = [
        "// Auto-generated by scripts/generate_webui_embedded.py. Do not edit.",
        "#ifndef KASUMI_GENERATED_APPLICATION_WEBUI_EMBEDDED_HPP",
        "#define KASUMI_GENERATED_APPLICATION_WEBUI_EMBEDDED_HPP",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <span>",
        "#include <string_view>",
        "",
        "namespace kasumi::application::webui_embedded {",
        "",
        "struct Asset {",
        "    std::string_view path;",
        "    std::string_view content_type;",
        "    std::span<const std::uint8_t> data;",
        "    bool immutable = false;",
        "};",
        "",
        f"inline constexpr bool kAvailable = {available};",
        "",
    ]

    if files:
        parts.append("namespace detail {")
        for idx, (_, _, raw, _) in enumerate(files):
            parts.append(format_byte_array(f"kAssetBytes_{idx}", raw))
        parts.append(f"inline constexpr std::array<Asset, {len(files)}> kAssets{{{{")
        for idx, (url_path, content_type, raw, immutable) in enumerate(files):
            imm = "true" if immutable else "false"
            span_expr = (
                f"std::span<const std::uint8_t>{{kAssetBytes_{idx}, {len(raw)}u}}"
                if raw
                else "std::span<const std::uint8_t>{}"
            )
            parts.append(
                f'    Asset{{"{escape_cpp_string(url_path)}", '
                f'"{escape_cpp_string(content_type)}", {span_expr}, {imm}}},'
            )
        parts.append("}};")
        parts.append("} // namespace detail")
        parts.append("")
        parts.append("inline constexpr std::span<const Asset> assets() noexcept {")
        parts.append("    return detail::kAssets;")
        parts.append("}")
    else:
        parts.append("inline constexpr std::span<const Asset> assets() noexcept {")
        parts.append("    return {};")
        parts.append("}")

    parts.append("")
    parts.append("} // namespace kasumi::application::webui_embedded")
    parts.append("")
    parts.append("#endif // KASUMI_GENERATED_APPLICATION_WEBUI_EMBEDDED_HPP")
    parts.append("")
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate embedded Web UI header")
    parser.add_argument("--dist", required=True, type=Path, help="Path to web/dist")
    parser.add_argument("--output", required=True, type=Path, help="Output header path")
    parser.add_argument(
        "--enabled",
        choices=("0", "1"),
        default="1",
        help="Whether Web UI embedding is enabled",
    )
    args = parser.parse_args()

    rendered = generate_header(args.dist, args.enabled == "1")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.output.is_file() and args.output.read_text(encoding="utf-8") == rendered:
        return 0
    args.output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
